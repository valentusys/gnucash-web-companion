import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
import ts from 'typescript';
const mobile=readFileSync(new URL('../src/lib/components/MobileNav.svelte',import.meta.url),'utf8');
const script=mobile.match(/<script lang="ts">([\s\S]*?)<\/script>/)[1];
const functions=ts.createSourceFile('mobile.ts',script,ts.ScriptTarget.Latest,true).statements.filter(ts.isFunctionDeclaration).map(n=>n.getText()).join('\n');
let focused=0,prevented=0;
const c=vm.createContext({menuOpen:true,menuButton:{focus:()=>focused++}});
vm.runInContext(ts.transpileModule(functions,{compilerOptions:{target:ts.ScriptTarget.ES2022}}).outputText,c);
assert.equal(vm.runInContext('typeof handleKeydown',c),'function','Escape must close an open navigation menu and restore focus');
vm.runInContext('handleKeydown',c)({key:'Tab',preventDefault:()=>prevented++});assert.equal(c.menuOpen,true);assert.equal(focused,0);
vm.runInContext('handleKeydown',c)({key:'Escape',preventDefault:()=>prevented++});assert.equal(c.menuOpen,false);assert.equal(focused,1);assert.equal(prevented,1);
vm.runInContext('handleKeydown',c)({key:'Escape',preventDefault:()=>prevented++});assert.equal(focused,1);assert.equal(prevented,1);
c.menuButton=null;c.menuOpen=true;vm.runInContext('closeMenu()',c);assert.equal(c.menuOpen,false);
assert.match(mobile,/<svelte:window onkeydown=\{handleKeydown\}/);
assert.match(mobile,/data-mobile-more[\s\S]*bind:this=\{menuButton\}/);
const desktop=readFileSync(new URL('../src/lib/components/DesktopNav.svelte',import.meta.url),'utf8');
assert.match(desktop,/flex-wrap/);assert.match(desktop,/form method="POST" action="\/logout"/);
assert.doesNotMatch(desktop,/overflow-(?:hidden|x-hidden)/,'Do not clip controls to hide overflow');
console.log('QA-11 navigation layout and Escape focus branches passed');
const ci=readFileSync(new URL('../../../.github/workflows/ci.yml',import.meta.url),'utf8');
assert.match(ci,/npm run test:qa-header/);assert.match(ci,/QA_HEADER=1 QA_SCENARIO=money node scripts\/test-qa-regressions-browser\.mjs/);
